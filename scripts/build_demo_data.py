"""Build demo/data.js, the dataset behind the static demo viewer (demo/index.html).

Runs the pipeline in deterministic mode over a directory of claims and writes
every result, the claim payloads and the synthetic document texts into one
JavaScript file. A plain <script> include works from file://, so the viewer
opens straight from disk with no server and no network access.

Usage, from the repository root:

    python scripts/build_demo_data.py                  # samples -> demo/data.js
    python scripts/build_demo_data.py --claims-dir DIR --out demo/data.js
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

# Allow running as a plain script from the repository root.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from adjudication.bootstrap import build_local_pipeline  # noqa: E402
from adjudication.core.ingestion import IngestionError, decode_payload  # noqa: E402
from adjudication.core.rules import default_rules  # noqa: E402
from adjudication.serialization import to_jsonable  # noqa: E402

HEADER = (
    "// Generated by scripts/build_demo_data.py - do not edit by hand.\n"
    "// Synthetic data only. Regenerate with: python scripts/build_demo_data.py\n"
)


def build(claims_dir: Path, documents_dir: Path, extractions_dir: Path, expected_file: Path | None) -> str:
    """Return the full contents of data.js for the given inputs."""
    pipeline = build_local_pipeline(documents_dir=documents_dir, extractions_dir=extractions_dir, deterministic=True)
    policy = pipeline.policy
    scenarios = _scenarios(expected_file)

    cases = []
    for path in sorted(claims_dir.glob("*.json")):
        raw = path.read_bytes()
        result = pipeline.process_raw(raw, source=path.name)
        payload = _payload(raw)
        cases.append(
            {
                "key": path.stem,
                "scenario": scenarios.get(path.name, {}).get("scenario"),
                "note": scenarios.get(path.name, {}).get("note"),
                "claim": payload,
                "documents": _document_texts(payload, documents_dir),
                "result": to_jsonable(result),
            }
        )

    data = {
        "schema_version": "1.0",
        "generated_by": "scripts/build_demo_data.py",
        "deterministic": True,
        "policy": {
            "version": policy.version,
            "digest": policy.digest,
            "min_field_confidence": policy.min_field_confidence,
            "amount_tolerance": to_jsonable(policy.amount_tolerance),
            "submission_window_days": policy.submission_window_days,
            "allowed_currencies": sorted(policy.allowed_currencies),
            "required_fields": list(policy.required_fields),
        },
        "rules": [{"rule_id": r.rule_id, "title": r.title, "severity": str(r.severity)} for r in default_rules()],
        "cases": cases,
    }
    return HEADER + "window.ADJUDICATION_DEMO = " + json.dumps(data, indent=2) + ";\n"


def _scenarios(expected_file: Path | None) -> dict[str, Any]:
    if expected_file is None or not expected_file.is_file():
        return {}
    return json.loads(expected_file.read_text(encoding="utf-8")).get("outcomes", {})


def _payload(raw: bytes) -> Any:
    try:
        return decode_payload(raw)
    except IngestionError:
        return None


def _document_texts(payload: Any, documents_dir: Path) -> dict[str, str]:
    """Source text of each referenced plain-text document that exists on disk."""
    texts: dict[str, str] = {}
    documents = payload.get("documents") if isinstance(payload, dict) else None
    if not isinstance(documents, list):
        return texts
    root = documents_dir.resolve()
    for document in documents:
        if not isinstance(document, dict) or document.get("media_type") != "text/plain":
            continue
        name, document_id = document.get("file"), document.get("document_id")
        if not isinstance(name, str) or not isinstance(document_id, str):
            continue
        path = (root / name).resolve()
        if path.parent == root and path.is_file():
            texts[document_id] = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    return texts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--claims-dir", default="samples/claims")
    parser.add_argument("--documents-dir", default="samples/documents")
    parser.add_argument("--extractions-dir", default="samples/extractions")
    parser.add_argument("--expected", default="samples/expected_outcomes.json", help="optional scenario descriptions")
    parser.add_argument("--out", default="demo/data.js")
    args = parser.parse_args(argv)

    content = build(Path(args.claims_dir), Path(args.documents_dir), Path(args.extractions_dir), Path(args.expected))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {out} ({len(content.encode('utf-8')) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
